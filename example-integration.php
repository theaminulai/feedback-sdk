// 6. STORING THE API KEY SAFELY
// ─────────────────────────────────────────────────────────────────────────────

/*
 * Never hard-code the API key directly in your plugin if it will be
 * distributed publicly (WordPress.org, GitHub, etc.).
 *
 * Recommended approaches:
 *
 * A) Define in wp-config.php (best for single server):
 *    define( 'WPMET_FEEDBACK_KEY', 'fk_xxxxxxxxxxxxxxxx' );
 *
 * B) Define in your plugin's private config file (not committed to git):
 *    // config.php  (in .gitignore)
 *    define( 'WPMET_FEEDBACK_KEY', 'fk_xxxxxxxxxxxxxxxx' );
 *
 * C) For distributed plugins — it's acceptable to include the key directly
 *    since the key only allows WRITING feedback (not reading data).
 *    The server's rate limiter and HMAC signature provide the protection.
 *
 *    'api_key' => 'fk_xxxxxxxxxxxxxxxx',  // write-only, rate-limited
 */
