/*
 * The SDK automatically collects these values from WordPress — you don't
 * need to pass them in the config:
 *
 *   site_url      → get_site_url()
 *   admin_email   → get_option('admin_email')    (empty if gdpr unchecked)
 *   wp_version    → get_bloginfo('version')
 *   php_version   → PHP_MAJOR_VERSION.PHP_MINOR_VERSION
 *   locale        → get_locale()
 *   timestamp     → current_time('mysql')
 *
 * These come from your config:
 *   plugin_name, plugin_slug, plugin_version, is_pro
 *
 * These come from the user's modal input:
 *   reason        → the selected reason key (e.g. 'missing-feature')
 *   message       → text typed in the textarea
 *   competitor    → only filled if the user typed something (no dedicated field by default)
 *
 * These are added by the server (not sent by SDK):
 *   country       → resolved from IP address server-side
 *   ip_address    → detected server-side
 *   status        → defaults to 'new'
 *   created_at    → set by database DEFAULT
 */


