/**
 * Add custom data to the payload before it is sent to the server.
 * You can add any extra field here — the server's collect endpoint
 * will receive it (though only the documented fields are stored in the DB).
 *
 * @param array  $payload The full data array being sent.
 * @param string $slug    Your plugin slug.
 * @return array
 */
add_filter( 'feedback_sdk/payload', function ( array $payload, string $slug ): array {

    // Add any extra context you want logged on the server.
    $payload['active_theme']    = get_template();
    $payload['multisite']       = is_multisite() ? 'yes' : 'no';
    $payload['plugin_pro_plan'] = get_option( 'my_plugin_plan', 'free' );

    return $payload;

}, 10, 2 );


/**
 * React after the feedback has been sent (or failed).
 * Use for custom logging, Slack notifications, etc.
 *
 * @param string $slug    Your plugin slug.
 * @param bool   $success Whether wp_remote_post succeeded.
 * @param array  $payload The data that was sent.
 */
add_action( 'feedback_sdk/after_send', function ( string $slug, bool $success, array $payload ): void {

    if ( ! $success ) {
        // Example: log failures to your own error tracking.
        error_log( "[{$slug}] Feedback SDK send failed. Reason: " . ( $payload['reason'] ?? 'unknown' ) );
    }

}, 10, 3 );


/**
 * Modify the reasons list at runtime (server-side, before JS localization).
 * Useful for dynamically showing/hiding reasons based on user role, plan, etc.
 *
 * @param array  $reasons Array of reason objects {key, icon, label, ph}.
 * @param string $slug    Your plugin slug.
 * @return array
 */
add_filter( 'feedback_sdk/reasons', function ( array $reasons, string $slug ): array {

    // Example: hide "Too expensive" for users who already have a Pro licence.
    if ( my_plugin_user_has_licence() ) {
        $reasons = array_filter( $reasons, fn( $r ) => $r['key'] !== 'too-expensive' );
        $reasons = array_values( $reasons ); // re-index
    }

    return $reasons;

}, 10, 2 );


